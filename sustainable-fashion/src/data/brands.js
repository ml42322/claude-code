export const brandById = (id) => BRANDS.find((b) => b.id === id);

export const scoreBrand = (b, weights) => {
  let tot = 0, wsum = 0;
  for (const k of LENS_KEYS) { const w = weights?.[k] ?? 1; tot += b.scores[k] * w; wsum += w; }
  return wsum ? Math.round(tot / wsum) : 0;
};

